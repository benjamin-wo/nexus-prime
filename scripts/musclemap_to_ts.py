#!/usr/bin/env python3
"""Generate web/src/health/body/paths.ts from the MuscleMap SVG path data (stdlib only).

Source: https://github.com/melihcolpan/MuscleMap (MIT), pinned to SHA below. The Swift files
under Sources/MuscleMap/Data/ hold one BodyPartPathData(slug:, common:, left:, right:) per
region; this script fetches them and writes the male front and back views as a TypeScript
module.

    python3 scripts/musclemap_to_ts.py           # fetch and (re)write paths.ts
    python3 scripts/musclemap_to_ts.py --check   # exit 1 if paths.ts is not what the source makes

To move to a newer MuscleMap, change SHA, run the script and review the diff.
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.request
from pathlib import Path

REPO = "melihcolpan/MuscleMap"
SHA = "d53ddf4d480b65979f1008b203e6b6eda0e67e54"
DATA_DIR = "Sources/MuscleMap/Data"
OUT = Path(__file__).resolve().parent.parent / "web/src/health/body/paths.ts"

# view -> (Swift file, enum holding the paths)
VIEWS = {"front": "MaleFrontPaths", "back": "MaleBackPaths"}
# BodyViewBox.maleFront / maleBack in BodyPathData.swift: "x y width height".
VIEWBOX_RE = (
    r"static let {name} = BodyViewBox\(\s*origin: CGPoint\(x: (\d+), y: (\d+)\),"
    r"\s*size: CGSize\(width: (\d+), height: (\d+)\)"
)
SIDE = {"common": "both", "left": "left", "right": "right"}


def fetch(name: str) -> str:
    url = f"https://raw.githubusercontent.com/{REPO}/{SHA}/{DATA_DIR}/{name}.swift"
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read().decode("utf-8")


def parse_viewbox(src: str, name: str) -> str:
    m = re.search(VIEWBOX_RE.format(name=name), src)
    if not m:
        raise SystemExit(f"viewBox {name} not found in BodyPathData.swift")
    return " ".join(m.groups())


def parse_paths(src: str) -> dict[str, list[tuple[str, str]]]:
    """slug -> [(side, d), ...] in source order."""
    out: dict[str, list[tuple[str, str]]] = {}
    for block in src.split("BodyPartPathData(")[1:]:
        slug = re.search(r"slug:\s*\.(\w+)", block)
        if not slug:
            raise SystemExit("a BodyPartPathData has no slug")
        entries: list[tuple[str, str]] = []
        for label, body in re.findall(r"\b(common|left|right):\s*\[(.*?)\]", block, re.S):
            for d in re.findall(r'"([^"]+)"', body):
                entries.append((SIDE[label], re.sub(r"\s+", " ", d).strip()))
        if entries:
            out[slug.group(1)] = entries
    return out


def render() -> str:
    boxes = fetch("BodyPathData")
    views = {v: parse_paths(fetch(f)) for v, f in VIEWS.items()}
    viewbox = {"front": parse_viewbox(boxes, "maleFront"), "back": parse_viewbox(boxes, "maleBack")}
    regions = sorted({r for v in views.values() for r in v})
    lines = [
        "// GENERATED by scripts/musclemap_to_ts.py: do not edit; "
        "run the script (or --check) instead.",
        f"// Source: https://github.com/{REPO} @ {SHA}",
        "// SVG path data for the male front and back body views. MIT, see NOTICE.md.",
        "",
        'export type Side = "both" | "left" | "right";',
        'export type View = "front" | "back";',
        f"export type Region = {' | '.join(repr(r).replace(chr(39), chr(34)) for r in regions)};",
        "",
        "/** One drawn shape: which side of the body it is on, and its SVG path data. */",
        "export type RegionPath = readonly [side: Side, d: string];",
        "",
        "/** The viewBox of each view (x y width height): the two views share one drawing, "
        "so each shows its own window. */",
        "export const VIEW_BOX: Record<View, string> = {",
    ]
    lines += [f'  {v}: "{viewbox[v]}",' for v in VIEWS]
    lines += [
        "};",
        "",
        "export const PATHS: Record<View, Partial<Record<Region, readonly RegionPath[]>>> = {",
    ]
    for v in VIEWS:
        lines.append(f"  {v}: {{")
        for region in sorted(views[v]):
            lines.append(f"    {region}: [")
            lines += [f'      ["{side}", "{d}"],' for side, d in views[v][region]]
            lines.append("    ],")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--check", action="store_true", help="do not write; exit 1 if paths.ts is out of date"
    )
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run python3 scripts/musclemap_to_ts.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} is up to date ({SHA[:7]})")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
