"""The bundled exercise catalogue (free-exercise-db, public domain).

``catalogue.json`` is generated by ``scripts/import_free_exercise_db.py``; never edit it by
hand. The app upserts it into the ``exercises`` table at startup.
"""

import json
from pathlib import Path

from nexus.domain.gym import Exercise

CATALOGUE = Path(__file__).with_name("catalogue.json")


def load_catalogue(path: Path = CATALOGUE) -> list[Exercise]:
    return [Exercise.from_dict(entry) for entry in json.loads(path.read_text(encoding="utf-8"))]
