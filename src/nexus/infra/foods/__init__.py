"""The bundled food databases: one JSON file of foods per source, all through one loader.

``usda.json`` (USDA FoodData Central, public domain) is generated by
``scripts/import_usda_fdc.py``; never edit it by hand. The app upserts every ``*.json`` here
into the ``foods`` table at startup. A source's file holds a list of entries as ``Food.from_dict``
reads them: ``id`` (``<source>:<the source's own id>``), ``source``, ``name``, ``aliases``,
``kcal``, ``protein_g``, ``carbs_g``, ``fat_g`` and ``fibre_g`` per 100 g (fibre may be null),
and ``portions`` (``{label, grams}``).

SG FoodID (Health Promotion Board, Singapore) is the intended second source, for hawker and
local dishes, as ``sgfoodid.json`` with ``source`` ``sgfoodid``. Its terms of use (6 Oct 2025,
https://file.go.gov.sg/termsofuse-hpbsgfoodid.pdf) grant a worldwide, perpetual, royalty-free,
non-exclusive licence to use, copy, distribute, modify and adapt the data, on two conditions:
HPB's attribution text must be shown, and nothing may imply HPB's endorsement. So when that
file is added: copy HPB's attribution wording from the terms into ``NOTICE.md`` and show it
wherever those foods' values are shown. The data is not downloaded yet and there is no stub;
no nutrient value, hawker dishes included, is ever written by hand.
"""

import json
from decimal import Decimal
from pathlib import Path
from typing import Any

from nexus.domain.errors import InvalidInput
from nexus.domain.nutrition import Food

FOODS_DIR = Path(__file__).parent


def load_file(path: Path) -> list[Food]:
    entries: list[Any] = json.loads(path.read_text(encoding="utf-8"), parse_float=Decimal)
    return [Food.from_dict(entry) for entry in entries]


def load_foods(directory: Path = FOODS_DIR) -> list[Food]:
    """Every food in every ``*.json`` file in the directory, in file-name order. An id used
    twice is an error: two sources must not claim the same food."""
    foods = [food for path in sorted(directory.glob("*.json")) for food in load_file(path)]
    ids = [f.id for f in foods]
    if len(set(ids)) != len(ids):
        raise InvalidInput("a food id appears in more than one place")
    return foods
